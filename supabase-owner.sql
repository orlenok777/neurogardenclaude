-- НейроСад: назначение владельца панели. Выполняется ОДИН раз, вручную, одним исполнителем,
-- только после того как Рома явно назвал свой аккаунт и лично вошёл на сайт через Google.
--
-- Как получить UID: после входа через Google сайт показывает во вкладке «Панель Ромы» строку
-- «Идентификатор аккаунта: ...». UID не секрет, его можно переслать исполнителю.
--
-- Перед запуском замените нули на этот UID. Запрос ничего не сделает (INSERT 0 0), если:
--   * такого пользователя нет в Supabase Auth,
--   * его почта не подтверждена,
--   * у него нет входа через Google,
--   * владелец уже назначен.
-- Ожидаемый ответ при успехе: INSERT 0 1.

insert into public.ng_owner (uid)
select u.id
from auth.users u
where u.id = '00000000-0000-0000-0000-000000000000'::uuid
  and u.email_confirmed_at is not null
  and exists (select 1 from auth.identities i where i.user_id = u.id and i.provider = 'google')
  and not exists (select 1 from public.ng_owner);

-- Проверка без раскрытия личных данных: сколько владельцев назначено (должно быть 1).
select count(*) as owners from public.ng_owner;

